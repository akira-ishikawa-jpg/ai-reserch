from typing import List

def generate_consult_prompts(issue: str) -> List[str]:
    """
    1つの課題文から観点を変えた5つの相談プロンプトを生成
    - 抽象度
    - 相談者の立場
    - 制約条件
    - 目的の違い
    などをバリエーションとして含める
    """
    base = issue.strip()
    prompts = [
        f"この課題を解決するためのサービスや方法を教えてください。課題: {base}",
        f"中小企業の経営者として、次の課題を解決したいです。どんなサービスが考えられますか？課題: {base}",
        f"コストや導入工数に制約がある場合、どのような解決策が考えられますか？課題: {base}",
        f"この課題の根本的な解決を目指す場合、どんなアプローチやサービスが有効ですか？課題: {base}",
        f"現場担当者の視点で、次の課題に対する実践的な解決策を提案してください。課題: {base}"
    ]
    return prompts
