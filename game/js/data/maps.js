// タイル通行判定
function isTilePassable(tileType) {
  return tileType === TILE.EMPTY || tileType === TILE.FLOOR ||
         tileType === TILE.DOOR || tileType === TILE.ENTRANCE ||
         tileType === TILE.SAVE;
}

